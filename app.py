# ============================== TAB 1 ====================================
with tab1:
    col_input, col_result = st.columns([1.3, 1])

    with col_input:
        st.subheader("Paste your essay")
        sample_options = {
            "— Select a sample —": "",
            "Sample: Human-style essay": (
                "I remember the first time I visited my grandmother's farm during "
                "summer break. The smell of fresh hay and the sound of chickens "
                "in the yard made me feel calm in a way the city never did. My "
                "cousins and I would spend hours building forts out of old wood "
                "planks, arguing about whose fort was better, then forgetting the "
                "argument entirely once dinner was ready. Looking back now, I "
                "realize those messy, unplanned afternoons taught me more about "
                "patience and creativity than any classroom ever did."
            ),
            "Sample: AI-style essay": (
                "In today's rapidly evolving digital landscape, the integration of "
                "artificial intelligence into everyday life has become increasingly "
                "prevalent. This essay explores the multifaceted implications of "
                "AI adoption, examining both its benefits and challenges. On one "
                "hand, AI systems offer unprecedented efficiency and convenience, "
                "streamlining processes across various industries. On the other "
                "hand, concerns regarding data privacy, job displacement, and "
                "ethical considerations continue to warrant careful attention. In "
                "conclusion, a balanced approach to AI implementation is essential "
                "for maximizing societal benefit while mitigating potential risks."
            ),
        }
        chosen_sample = st.selectbox("Try a sample essay (optional):", list(sample_options.keys()))

        default_text = sample_options[chosen_sample]
        user_text = st.text_area(
            "Essay text",
            value=default_text,
            height=320,
            placeholder="Paste an essay here (at least a few sentences for a reliable result)...",
            label_visibility="collapsed",
        )

        analyze_clicked = st.button("🔍 Analyze Essay", type="primary", use_container_width=True)

    with col_result:
        st.subheader("Result")
        if analyze_clicked:
            if not user_text or len(user_text.strip()) < 10:
                st.warning("Please enter a longer piece of text (at least a full sentence).")
            else:
                pred, proba = predict(user_text, model, vectorizer)
                if pred is None:
                    st.warning("Could not process this input. Please try different text.")
                else:
                    ai_prob = proba[1]
                    human_prob = proba[0]

                    if pred == 1:
                        st.error(f"### 🤖 Likely AI-Generated")
                    else:
                        st.success(f"### 🧑 Likely Human-Written")

                    st.metric("AI-Generated Probability", f"{ai_prob*100:.1f}%")

                    fig, ax = plt.subplots(figsize=(5, 1.2))
                    ax.barh([0], [human_prob], color="#4C72B0", label="Human")
                    ax.barh([0], [ai_prob], left=[human_prob], color="#DD8452", label="AI-Generated")
                    ax.set_xlim(0, 1)
                    ax.set_yticks([])
                    ax.set_xlabel("Probability")
                    ax.legend(loc="upper center", bbox_to_anchor=(0.5, -0.6), ncol=2, frameon=False)
                    for spine in ["top", "right", "left"]:
                        ax.spines[spine].set_visible(False)
                    st.pyplot(fig, use_container_width=True)

                    st.markdown("#### Text Statistics")
                    stats = text_stats(user_text)
                    stats_df = pd.DataFrame(stats.items(), columns=["Metric", "Value"])
                    st.dataframe(stats_df, hide_index=True, use_container_width=True)
        else:
            st.info("Enter or select an essay and click **Analyze Essay** to see the prediction.")

# ============================== TAB 2 ====================================
with tab2:
    st.subheader("Batch prediction from a CSV file")
    st.markdown(
        "Upload a CSV file with a column named **`text`** containing one essay per row. "
        "The app will predict a label for every row and let you download the results."
    )

    uploaded_file = st.file_uploader("Upload CSV", type=["csv"])

    if uploaded_file is not None:
        try:
            batch_df = pd.read_csv(uploaded_file)
        except Exception as e:
            st.error(f"Could not read the CSV file: {e}")
            batch_df = None

        if batch_df is not None:
            if "text" not in batch_df.columns:
                st.error("The uploaded CSV must contain a column named `text`.")
            else:
                if st.button("Run Batch Prediction", type="primary"):
                    with st.spinner("Analyzing essays..."):
                        cleaned = batch_df["text"].astype(str).apply(clean_text)
                        vecs = vectorizer.transform(cleaned)
                        preds = model.predict(vecs)
                        probas = model.predict_proba(vecs)[:, 1]

                        batch_df["prediction"] = np.where(preds == 1, "AI-Generated", "Human-Written")
                        batch_df["ai_probability"] = np.round(probas, 4)

                    st.success(f"Analyzed {len(batch_df)} essays.")
                    st.dataframe(
                        batch_df[["text", "prediction", "ai_probability"]].head(50),
                        use_container_width=True,
                    )

                    col_a, col_b = st.columns(2)
                    with col_a:
                        st.metric("Predicted Human", int((preds == 0).sum()))
                    with col_b:
                        st.metric("Predicted AI-Generated", int((preds == 1).sum()))

                    csv_out = batch_df.to_csv(index=False).encode("utf-8")
                    st.download_button(
                        "⬇️ Download Results as CSV",
                        data=csv_out,
                        file_name="authentitext_predictions.csv",
                        mime="text/csv",
                    )
    else:
        st.info("Upload a CSV file to get started, or try the Single Essay Check tab.")

