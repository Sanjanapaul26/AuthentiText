import re
import os
import joblib
import numpy as np
import pandas as pd
import streamlit as st
import matplotlib.pyplot as plt

# --------------------------------------------------------------------------
# Page configuration
# --------------------------------------------------------------------------
st.set_page_config(
    page_title="AuthentiText | AI Essay Detector",
    page_icon="📝",
    layout="wide",
    initial_sidebar_state="expanded",
)

MODEL_PATH = "outputs/best_model.pkl"
VECTORIZER_PATH = "outputs/tfidf_vectorizer.pkl"
MODEL_NAME_PATH = "outputs/model_name.txt"


# --------------------------------------------------------------------------
# Text cleaning (must mirror the notebook's preprocessing exactly)
# --------------------------------------------------------------------------
def clean_text(text: str) -> str:
    text = str(text).lower()
    text = re.sub(r"http\S+|www\S+", " ", text)
    text = re.sub(r"[^a-z\s]", " ", text)
    text = re.sub(r"\s+", " ", text).strip()
    return text


# --------------------------------------------------------------------------
# Cached resource loading
# --------------------------------------------------------------------------
@st.cache_resource
def load_artifacts():
    if not (os.path.exists(MODEL_PATH) and os.path.exists(VECTORIZER_PATH)):
        return None, None, None
    model = joblib.load(MODEL_PATH)
    vectorizer = joblib.load(VECTORIZER_PATH)
    model_name = "Model"
    if os.path.exists(MODEL_NAME_PATH):
        with open(MODEL_NAME_PATH) as f:
            model_name = f.read().strip()
    return model, vectorizer, model_name


def predict(text, model, vectorizer):
    cleaned = clean_text(text)
    if len(cleaned.strip()) == 0:
        return None, None
    vec = vectorizer.transform([cleaned])
    pred = model.predict(vec)[0]
    proba = model.predict_proba(vec)[0]
    return pred, proba


def text_stats(text: str) -> dict:
    words = text.split()
    sentences = re.split(r"[.!?]+", text)
    sentences = [s for s in sentences if s.strip()]
    word_count = len(words)
    char_count = len(text)
    sentence_count = max(len(sentences), 1)
    avg_word_len = round(char_count / word_count, 2) if word_count else 0
    avg_sentence_len = round(word_count / sentence_count, 2) if sentence_count else 0
    return {
        "Word Count": word_count,
        "Character Count": char_count,
        "Sentence Count": sentence_count,
        "Avg. Word Length": avg_word_len,
        "Avg. Words / Sentence": avg_sentence_len,
    }


